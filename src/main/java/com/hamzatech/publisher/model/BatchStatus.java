package com.hamzatech.publisher.model;

/**
 * نتيجة دفعة نشر كاملة. كانت الواجهة تعرض "اكتملت بنجاح" دائمًا حتى لو فشل كل مقال،
 * لأن نتيجة كل مقال كانت تُهمَل.
 */
public enum BatchStatus {

    /** لا عناوين في الملف. */
    NOTHING_TO_PUBLISH,

    /** كل المقالات نُشرت. */
    SUCCESS,

    /** كل العناوين منشورة على هذه الوجهة من قبل، فلم يُنشر شيء جديد. */
    ALL_SKIPPED,

    /** بعضها نجح وبعضها فشل. */
    PARTIAL_SUCCESS,

    /** لم ينجح أي مقال. */
    FAILED,

    /** أوقف المستخدم الدفعة قبل انتهائها. */
    CANCELLED
}
